import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync('app/src/main/assets/live.js','utf8');
const map=fs.readFileSync('app/src/main/java/ar/com/colectivos/consulta/MapActivity.kt','utf8');
const app=fs.readFileSync('app/src/main/java/ar/com/colectivos/consulta/MainActivity.kt','utf8');
const manifest=fs.readFileSync('app/src/main/AndroidManifest.xml','utf8');
const css=fs.readFileSync('app/src/main/assets/mobile.css','utf8');
const loc=html.indexOf('function validGeoPoint(');
const end=html.indexOf('function mainV3(){',loc);
assert.ok(loc>=0&&end>loc);
const ctx=vm.createContext({});
vm.runInContext(html.slice(loc,end),ctx);
const point=x=>vm.runInContext('validGeoPoint('+JSON.stringify(x)+')',ctx);
assert.ok(point({lat:-34.75,lon:-58.28,nombre:'Parada'}));
assert.equal(point({lat:null,lon:null}),null);
assert.equal(point({lat:0,lon:0}),null);
assert.equal(point({lat:100,lon:200}),null);
assert.ok(html.includes("native('map.show'"));
assert.ok(html.includes("function openRouteMap()"));
assert.ok(html.includes("function openStopsMap()"));
assert.ok(html.includes("function openArrivalsMap()"));
assert.ok(html.includes("function helpV3()"));
assert.ok(html.includes("makers.help=helpV3"));
assert.ok(html.includes("function loadRoute()"));
assert.ok(css.includes(".arrival-eta strong")&&css.includes("font-size:clamp(24px,6vw,32px)"));
assert.ok(manifest.includes('.MapActivity')&&manifest.includes('android:exported="false"'));
assert.ok(map.includes("setTileSource(TileSourceFactory.MAPNIK)"));
assert.ok(map.includes("BoundingBox.fromGeoPoints(points)"));
assert.ok(map.includes("Polyline(map)"));
assert.ok(app.includes('"map.show" ->'));
assert.ok(!app.includes('vercel.app'));
console.log('OK: mapas nativos, coords verificadas, guía, ETA visible y sin backend Vercel');
